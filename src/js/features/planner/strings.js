export function lang() {
    const l = window.getLang ? window.getLang() : (localStorage.getItem('jeju_lang') || 'zh');
    return S[l] ? l : 'zh';
}

export function tr(key, params = {}) {
    let text = S[lang()][key] ?? S.zh[key] ?? key;
    Object.keys(params).forEach(k => { text = text.replace(`{${k}}`, params[k]); });
    return text;
}

/** 운영자가 시트에서 읽는 접수 내용은 화면 언어와 무관하게 한국어로 기록한다 */
export function trKo(key) {
    return S.ko[key] ?? key;
}

/** {zh, ko, en} 형태의 데이터 필드에서 현재 언어 값을 꺼낸다 */
export function pick(obj) {
    if (!obj) return '';
    if (typeof obj === 'string') return obj;
    return obj[lang()] ?? obj.zh ?? obj.ko ?? '';
}

export function escapeHtml(s) {
    return String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
