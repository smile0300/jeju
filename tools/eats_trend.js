function priceText(p) {
    if (!p) return '';
    const [lo, hi] = p.split('-').map(Number);
    return `₩${lo <= 1 ? 1 : (lo * 1000).toLocaleString('en-US')}~${(hi * 1000).toLocaleString('en-US')}`;
}

